def build_memo(index: int, code: str, name: str, revenue: int,
               gross_margin: float, risk: str) -> str:
    headcount = 800 + index * 137
    return MEMO_TEMPLATE.format(
        code=code,
        name=name,
        revenue=revenue,
        prev_revenue=int(revenue * 0.91),
        gross_margin=f"{gross_margin:.1f}",
        prev_margin=f"{gross_margin - 1.4:.1f}",
        headcount=headcount,
        prev_headcount=headcount - 46,
        risk=risk,
        padding_a=_padding(index, 4),
        padding_b=_padding(index + 4, 4),
        padding_c=_padding(index + 8, 3),
    )


