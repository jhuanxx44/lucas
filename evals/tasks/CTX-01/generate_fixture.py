# 抽取文件与汇总表格式：grader 按此解析，instruction 里给出同样的格式说明。
EXTRACT_TEMPLATE = """code: {code}
name: {name}
revenue: {revenue}
gross_margin: {gross_margin}
risk: {risk}
rating: {rating}
"""

SUMMARY_HEADER = "| 代码 | 名称 | 营收 | 毛利率 | 风险 | 评级 |\n|---|---|---:|---:|---|---|\n"


def build_extract(code: str, name: str, revenue: int,
                  gross_margin: float, risk: str) -> str:
    return EXTRACT_TEMPLATE.format(
        code=code, name=name, revenue=revenue,
        gross_margin=f"{gross_margin:.1f}", risk=risk,
        rating=rating(gross_margin, risk),
    )


def build_summary() -> str:
    rows = "".join(
        f"| {code} | {name} | {revenue} | {gm:.1f} | {risk} | {rating(gm, risk)} |\n"
        for code, name, revenue, gm, risk in COMPANIES
    )
    return "# 尽调评级汇总\n\n" + SUMMARY_HEADER + rows


def main() -> None:
    memos = FIXTURE / "memos"
    memos.mkdir(parents=True, exist_ok=True)
    (FIXTURE / "extracts").mkdir(parents=True, exist_ok=True)
    # extracts/ 需存在但为空目录；git 不跟踪空目录，放 .gitkeep
